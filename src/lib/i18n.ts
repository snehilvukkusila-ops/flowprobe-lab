export type Locale = 'en' | 'de'

export const locale: Locale =
  typeof document !== 'undefined' && document.documentElement.lang === 'de'
    ? 'de'
    : 'en'

export function t(key: Key): string {
  return locale === 'de' ? de[key] : en[key]
}
